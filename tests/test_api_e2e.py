# tests/test_api_e2e.py

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fastapi.testclient import TestClient
from src.api.main import app

sample_policy = """# Access Control & Secret Management

## Section 1: API Token Allocation
All microservice-to-microservice calls must authenticate using tokens generated by Vault.
Token lifetimes are strictly capped at 3600 seconds.

## Section 2: Error Code SEC-4039
SEC-4039 indicates an unapproved credential handshake from an untrusted subnet.
Upon detecting SEC-4039, the security controller permanently revokes the client cert.
"""

def run_integration_test():
    with TestClient(app) as client:
        print("Testing /healthz...")
        health_resp = client.get("/healthz")
        assert health_resp.status_code == 200
        print(f"Health Response: {health_resp.json()}")

        print("\nIngesting Sample Policy...")
        ingest_payload = {
            "document_name": "vault_policy.md",
            "content": sample_policy
        }
        ingest_resp = client.post("/api/v1/ingest", json=ingest_payload)
        assert ingest_resp.status_code == 201
        print(f"Ingest Response: {ingest_resp.json()}")

        print("\nExecuting Hybrid Retrieval Query...")
        search_payload = {
            "query": "What triggers SEC-4039 revocation?",
            "top_k": 2
        }
        retrieve_resp = client.post("/api/v1/retrieve", json=search_payload)
        assert retrieve_resp.status_code == 200
        results = retrieve_resp.json()["results"]

        print(f"Retrieved {len(results)} chunks:")
        for res in results:
            print(f"- Rank {res['rrf_rank']} (Score {res['rrf_score']}): {res['section_path']}")
            print(f"  Content snippet: {res['content'][:80]}...")

        # Assert Section 2 is ranked #1 due to SEC-4039 keyword + semantic match
        assert "SEC-4039" in results[0]["section_path"]
        print("\nIntegration test passed successfully!")

if __name__ == "__main__":
    run_integration_test()